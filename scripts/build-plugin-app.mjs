import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

const result = await build({
	entryPoints: ["src/plugin/app.ts"],
	bundle: true,
	format: "iife",
	platform: "browser",
	target: "es2022",
	minify: true,
	write: false,
	outdir: "dist/plugin-app",
});

const javascript = result.outputFiles.find((file) => file.path.endsWith(".js"))?.text;
const stylesheet = result.outputFiles.find((file) => file.path.endsWith(".css"))?.text;
if (!javascript || !stylesheet) throw new Error("The plugin app bundle is incomplete.");

const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>styleguide.fyi</title><style>${stylesheet.replace(/<\/style/gi, "<\\/style")}</style></head><body><div id="app"></div><script>${javascript.replace(/<\/script/gi, "<\\/script")}</script></body></html>`;
await writeFile("src/plugin/app.generated.ts", `// Generated by scripts/build-plugin-app.mjs. Do not edit.\nexport const PLUGIN_APP_HTML = ${JSON.stringify(html)};\n`);
console.log(`Built MCP app resource (${Buffer.byteLength(html)} bytes).`);
